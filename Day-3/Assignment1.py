# Question - take input in celcius and print its equivalent in fahrenhecit and kelvin.
# (use explicit conversion and arithmetic operators)
# Formula-->>
# Fahrenheit = (c * 9/5) + 32
# Kelvin = c + 273.15

c = float(input("Enter temperature in Celcius: "))

print("Fahrenheit:" , (c * 9/5) + 32)
print("Kelvin:" , (c + 273.15))
